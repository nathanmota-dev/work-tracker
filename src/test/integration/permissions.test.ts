import { afterAll, beforeAll, expect, test } from "vitest";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { WebSocket } from "ws";
import type { PermissionRequest, PermissionSnapshot } from "../../acp/permission-types.ts";
const previous = { ...process.env };
const home = mkdtempSync(join(tmpdir(), "work-tracker-permissions-"));
process.env.WORK_TRACKER_HOME = home;
process.env.WORK_TRACKER_RESOURCES = resolve("resources");
process.env.WORK_TRACKER_CLI = resolve("out/cli/work-tracker.cjs");
const { saveConfig } = await import("../../paths.ts");
const { startBackend } = await import("../../server/index.ts");
const { db } = await import("../../db/index.ts");
const { permissionStore } = await import("../../acp/permission-store.ts");
let backend: Awaited<ReturnType<typeof startBackend>>;
let socket: WebSocket;
const api = (path: string, body?: unknown, token?: string) => fetch(`${backend.address}/api/${path}?token=${token ?? backend.token}`, { ...(body === undefined ? {} : { method: "POST", body: JSON.stringify(body) }) });
const snapshot = async () => (await (await api("acp/permissions")).json()) as PermissionSnapshot;
const records = () => { try { return readFileSync(join(home, "permissions.jsonl"), "utf8").trim().split("\n").map(line => JSON.parse(line)); } catch { return []; } };
const answer = (req: PermissionRequest, optionId?: string, remember = "once") => api("acp/permissions/answer", { id: req.id, sessionId: req.sessionId, runId: req.runId, optionId, remember });
beforeAll(async () => {
  saveConfig({ acp: { opencode: { command: process.execPath, args: [resolve("src/test/fixtures/permission-agent.cjs")], env: { PERMISSION_RECORD: join(home, "permissions.jsonl") } } } });
  backend = await startBackend();
  socket = new WebSocket(`ws://127.0.0.1:${backend.port}/ws?token=${backend.token}`);
  await new Promise<void>(resolve => socket.once("open", resolve));
});
afterAll(async () => { socket?.terminate(); await backend?.close(); rmSync(home, { recursive: true, force: true }); process.env = previous; });
async function run(): Promise<PermissionRequest> {
  await expect.poll(async () => (await api("acp/run", { provider: "opencode", skill: "synthetic" })).status).toBe(200);
  await expect.poll(async () => (await snapshot()).pending.length).toBe(1);
  return (await snapshot()).pending[0]!;
}
test("authenticated exact decisions, duplicate/stale protection, session rules, cancellation and persistence", async () => {
  const first = await run();
  expect((await snapshot()).execution).toMatchObject({ runId: first.runId, sessionId: first.sessionId, status: "waiting_for_permission" });
  expect(records()).toEqual([]); // The real ACP process is still waiting.
  expect((await api("acp/permissions/answer", { ...first, optionId: "allow-exact" }, "invalid")).status).toBe(403);
  expect((await answer(first, "invented")).status).toBe(400);
  expect((await api("acp/permissions/answer", { ...first, runId: "old", optionId: "allow-exact" })).status).toBe(409);
  expect((await api("acp/permissions/answer", { ...first, sessionId: "old", optionId: "allow-exact" })).status).toBe(409);
  db().exec("CREATE TRIGGER fail_permission_rule BEFORE INSERT ON meta WHEN NEW.key = 'agent_tool_allowlist' BEGIN SELECT RAISE(ABORT, 'Synthetic storage failure'); END");
  expect((await answer(first, "allow-exact", "persistent")).status).toBe(500);
  expect(records()).toEqual([]);
  expect((await snapshot()).rules).toEqual([]);
  expect((await snapshot()).history.find(item => item.id === first.id)?.status).toBe("pending");
  db().exec("DROP TRIGGER fail_permission_rule");
  expect((await answer(first, "allow-exact", "session")).status).toBe(200);
  expect((await answer(first, "allow-exact")).status).toBe(409);
  await expect.poll(() => records().length).toBe(2);
  expect(records()).toEqual([{ outcome: { outcome: "selected", optionId: "allow-exact" } }, { outcome: { outcome: "selected", optionId: "allow-exact" } }]);
  await expect.poll(async () => (await snapshot()).pending[0]?.tool).toBe("linkedin_search_jobs");
  const other = (await snapshot()).pending[0]!;
  expect((await answer(other, "refuse-exact")).status).toBe(200);
  await expect.poll(() => records().length).toBe(3);
  expect(records().at(-1)).toEqual({ outcome: { outcome: "selected", optionId: "refuse-exact" } });
  await expect.poll(async () => (await snapshot()).sessionRules.length).toBe(0);
  const next = await run();
  expect((await answer(first, "allow-exact")).status).toBe(409);
  expect(next.id).not.toBe(first.id);
  expect((await answer(next, "allow-exact", "persistent")).status).toBe(200);
  await expect.poll(async () => (await snapshot()).pending[0]?.tool).toBe("linkedin_search_jobs");
  await answer((await snapshot()).pending[0]!, "refuse-exact");
  await expect.poll(async () => (await snapshot()).pending.length).toBe(0);
  expect((await snapshot()).rules).toEqual([{ provider: "opencode", tool: "linkedin_get_person_profile" }]);
  permissionStore.save({ ...first, id: "abandoned", status: "pending" });
  await backend.close();
  backend = await startBackend();
  socket = new WebSocket(`ws://127.0.0.1:${backend.port}/ws?token=${backend.token}`);
  await new Promise<void>(resolve => socket.once("open", resolve));
  expect((await snapshot()).history.some(item => item.optionId === "allow-exact" && item.remember === "persistent")).toBe(true);
  expect((await snapshot()).history.find(item => item.id === "abandoned")).toMatchObject({ status: "cancelled", reason: "App restarted" });
  await api("acp/run", { provider: "opencode", skill: "synthetic" });
  await expect.poll(async () => (await snapshot()).pending[0]?.tool).toBe("linkedin_search_jobs");
  await answer((await snapshot()).pending[0]!, "refuse-exact");
  await expect.poll(async () => (await snapshot()).pending.length).toBe(0);
  expect((await api("acp/permissions/rule", { provider: "opencode", tool: "linkedin_get_person_profile", enabled: false })).status).toBe(200);
  const revoked = await run();
  await api("acp/cancel", {});
  await expect.poll(async () => (await snapshot()).pending.length).toBe(0);
  expect((await snapshot()).history.find(item => item.id === revoked.id)?.status).toBe("cancelled");
  await expect.poll(async () => (await api("acp/run", { provider: "opencode", skill: "synthetic" })).status).toBe(200);
  await expect.poll(async () => (await snapshot()).pending.length).toBe(1);
  const disconnected = (await snapshot()).pending[0]!;
  socket.terminate();
  await expect.poll(async () => (await snapshot()).pending.length).toBe(0);
  expect((await snapshot()).history.find(item => item.id === disconnected.id)).toMatchObject({ status: "cancelled", reason: "Disconnected" });
  await expect.poll(async () => (await snapshot()).execution?.status).toBe("cancelled");
});
