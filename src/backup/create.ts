import { copyFileSync, existsSync, mkdirSync, readdirSync, realpathSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative } from "node:path";
import { db } from "../db/index.ts";
import { readVersion, rowCounts } from "../db/migrations.ts";
import { snapshotDatabase } from "../db/snapshot.ts";
import { Database } from "../db/sqlite.ts";
import { paths } from "../paths.ts";
import { VERSION } from "../version.gen.ts";
import {
  ARTIFACTS_DIR, BACKUP_FORMAT, BACKUP_FORMAT_VERSION, BackupError, CONFIG_FILE, DATABASE_FILE, MANIFEST_FILE, fileDigest, summarize,
  type BackupFile, type BackupManifest, type BackupSummary, type ExcludedSource,
} from "./format.ts";

/** True when `path` is `root` itself or a descendant of it. */
export function isInside(root: string, path: string): boolean {
  const rel = relative(root, path);
  return !rel.startsWith("..") && !isAbsolute(rel);
}

/** An existing absolute directory, resolved through symlinks. */
export function existingDirectory(value: unknown, label: string): string {
  if (typeof value !== "string" || !isAbsolute(value.trim())) throw new BackupError(`Choose an absolute ${label} folder.`);
  try {
    const path = realpathSync(value.trim());
    if (statSync(path).isDirectory()) return path;
  } catch { /* reported below */ }
  throw new BackupError(`The ${label} folder does not exist.`);
}

function excludedSources(): ExcludedSource[] {
  const local: [ExcludedSource["kind"], string, string][] = [
    ["browser-session", join(paths.home, "browsers"), "Browser sign-in sessions belong to this device. Sign in again after restoring."],
    ["agent-credentials", join(paths.home, "agents"), "Agent credentials and caches stay on this device."],
    ["agent-workspace", paths.workspace, "Agent skills are regenerated by Work Tracker setup."],
    ["backups", paths.backups, "Earlier backups and migration snapshots are not copied into new backups."],
  ];
  const excluded = local.filter(([, path]) => existsSync(path)).map(([kind, path, reason]) => ({ kind, path, reason }));
  // The base resume's LaTeX is generated again from the profile, so only the profile files matter.
  if (existsSync(paths.profile)) excluded.push({ kind: "resume-source", path: paths.profile, reason: "Your profile files (resume data, LinkedIn export and resume PDFs) are not copied. Keep a separate copy of them." });
  return excluded;
}

/** Copy the artifact tree; symbolic links are never followed and are reported instead. */
function copyArtifacts(target: string, excluded: ExcludedSource[]): string[] {
  const copied: string[] = [];
  function visit(directory: string) {
    for (const item of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, item.name);
      const name = relative(paths.artifacts, path).replaceAll("\\", "/");
      if (item.isSymbolicLink()) excluded.push({ kind: "symlink", path, reason: "Linked files are not copied into backups." });
      else if (item.isDirectory()) visit(path);
      else if (item.isFile()) {
        const destination = join(target, ARTIFACTS_DIR, name);
        mkdirSync(dirname(destination), { recursive: true, mode: 0o700 });
        copyFileSync(path, destination);
        copied.push(`${ARTIFACTS_DIR}/${name}`);
      }
    }
  }
  if (existsSync(paths.artifacts)) visit(paths.artifacts);
  return copied;
}

function databaseFacts(path: string): Pick<BackupManifest, "schemaVersion" | "counts"> {
  const copy = new Database(path, { readOnly: true });
  try { return { schemaVersion: Number(readVersion(copy)), counts: Object.fromEntries(rowCounts(copy)) }; }
  finally { copy.close(); }
}

function writeContents(target: string): BackupManifest {
  snapshotDatabase(db(), join(target, DATABASE_FILE));
  const listed: [BackupFile["kind"], string][] = [["database", DATABASE_FILE]];
  if (existsSync(paths.config)) {
    mkdirSync(dirname(join(target, CONFIG_FILE)), { recursive: true, mode: 0o700 });
    copyFileSync(paths.config, join(target, CONFIG_FILE));
    listed.push(["config", CONFIG_FILE]);
  }
  const excluded = excludedSources();
  for (const path of copyArtifacts(target, excluded)) listed.push(["artifact", path]);
  const files = listed.map(([kind, path]) => {
    const { size, sha256 } = fileDigest(join(target, path));
    return { path, kind, size, sha256 };
  });
  return {
    format: BACKUP_FORMAT, formatVersion: BACKUP_FORMAT_VERSION, appVersion: VERSION, createdAt: new Date().toISOString(),
    sourceHome: paths.home, ...databaseFacts(join(target, DATABASE_FILE)), files, excluded,
  };
}

/**
 * Write a versioned backup folder inside `destination`. Everything is written
 * to a `.partial` sibling first, so a failure never leaves a folder that looks
 * like a complete backup. Callers must refuse while an execution is active.
 */
export function createBackup(destination: unknown): BackupSummary {
  const parent = existingDirectory(destination, "destination");
  if (existsSync(paths.artifacts) && isInside(realpathSync(paths.artifacts), parent))
    throw new BackupError("Choose a destination outside the workspace artifact folder.");
  const stamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d+/, "");
  const target = join(parent, `work-tracker-backup-${stamp}`);
  if (existsSync(target)) throw new BackupError("A backup with this name already exists. Try again in a moment.", 409);
  const partial = `${target}.partial`;
  rmSync(partial, { recursive: true, force: true });
  mkdirSync(partial, { mode: 0o700 });
  try {
    const manifest = writeContents(partial);
    const text = `${JSON.stringify(manifest, null, 2)}\n`;
    writeFileSync(join(partial, MANIFEST_FILE), text, { mode: 0o600 });
    renameSync(partial, target);
    return summarize(target, manifest, text);
  } catch (error) {
    rmSync(partial, { recursive: true, force: true });
    throw error;
  }
}
