const personal = (page: Page) => page.getByRole('region', { name: 'Personal details' })

/** Opens a personal detail's section in place, fills that field and saves the section. */
async function editDetail(page: Page, label: string, value: string) {
  await personal(page).getByRole('button', { name: `Edit ${label}`, exact: true }).click()
  await personal(page).getByRole('textbox', { name: label, exact: true }).fill(value)
  await personal(page).getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Profile saved.' })).toBeVisible()
}

test('Profile / Answers: shared identity, validation, failed save and persistence', async ({ workspace, page }) => {
  await workspace.go('Profile')
  await expect(personal(page).getByRole('button', { name: 'Edit First name', exact: true })).toHaveAttribute('title', 'Add First name')
  await editDetail(page, 'First name', 'Taylor')
  await editDetail(page, 'Last name', 'Tester')
  await personal(page).getByRole('button', { name: 'Edit LinkedIn profile', exact: true }).click()
  const linkedin = personal(page).getByRole('textbox', { name: 'LinkedIn profile', exact: true })
  await linkedin.fill('https://linkedin.com/company/invalid')
  await expect(personal(page).getByRole('alert')).toContainText('LinkedIn profile URL')
  await expect(personal(page).getByRole('button', { name: 'Save changes' })).toBeDisabled()
  await linkedin.fill('https://linkedin.com/in/taylor-tester/')
  await workspace.fault('answer')
  await personal(page).getByRole('button', { name: 'Save changes' }).click()
  await expect(personal(page).getByRole('alert')).toContainText('Synthetic transport failure')
  await expect(linkedin).toHaveValue('https://linkedin.com/in/taylor-tester/')
  await personal(page).getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Profile saved.' })).toBeVisible()
  await editDetail(page, 'Email', 'taylor@example.com')
  for (const [label, value] of [['First name', 'Taylor'], ['Last name', 'Tester'], ['Email', 'taylor@example.com']])
    await expect(personal(page).getByRole('button', { name: `Edit ${label}`, exact: true })).toHaveAttribute('title', `${value} · Added by you`)
  await editDetail(page, 'Email', 'updated@example.com')
  await expect(page.getByRole('heading', { name: 'Taylor Tester', exact: true })).toBeVisible()
  await expect(page.getByText('updated@example.com', { exact: true }).first()).toBeVisible()
  await page.getByRole('tab', { name: 'LinkedIn', exact: true }).click()
  await page.getByRole('button', { name: 'Audit profile' }).click()
  await expect(page.getByRole('dialog', { name: 'Agent task' })).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Agent task' }).getByLabel('LinkedIn username')).toHaveValue('taylor-tester')
  await page.getByRole('button', { name: 'Run agent' }).click()
  await expect(page.getByText('Synthetic agent is working. Synthetic workflow completed.', { exact: true })).toBeVisible()
  expect(workspace.calls('prompt')[0]?.text).toContain('Name: Taylor Tester')
  await page.getByRole('dialog', { name: 'Agent task' }).getByRole('button', { name: 'Close', exact: true }).click()
  await workspace.go('Profile')
  await page.getByRole('tab', { name: 'LinkedIn', exact: true }).click()
  await expect(page.getByText('88 / 100', { exact: true })).toBeVisible()
  await workspace.restart()
  await workspace.go('Profile')
  await expect(personal(workspace.page).getByRole('button', { name: 'Edit Email', exact: true })).toContainText('updated@example.com')
})

test('Answers: create, duplicate guard, edit failure retry, cancellation and realtime changes', async ({ workspace, page }) => {
  await workspace.visit('/profile?tab=answers', 'Profile')
  await page.getByLabel('Advanced mode').check()
  await page.getByRole('button', { name: 'Add question' }).click()
  const editor = page.getByRole('region', { name: 'Add an answer' })
  await expect(editor.getByRole('button', { name: 'Save answer' })).toBeDisabled()
  await editor.getByLabel('Field key').fill('preferred_name')
  await editor.getByLabel('Category', { exact: true }).fill('contact')
  await editor.getByRole('textbox', { name: 'Answer', exact: true }).fill('Taylor')
  await workspace.fault('answer')
  await editor.getByRole('button', { name: 'Save answer' }).click()
  await expect(editor.getByRole('alert')).toContainText('Synthetic transport failure')
  await expect(editor.getByRole('textbox', { name: 'Answer', exact: true })).toHaveValue('Taylor')
  await editor.getByRole('button', { name: 'Save answer' }).click()
  await expect(editor).toHaveCount(0)
  expect(workspace.query("SELECT value FROM applicant_answers WHERE key = 'preferred_name'")[0]?.value).toBe('Taylor')
  await page.getByRole('button', { name: 'Add question' }).click()
  await editor.getByLabel('Field key').fill('preferred_name')
  await expect(editor.getByRole('button', { name: 'Save answer' })).toBeDisabled()
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(editor).toHaveCount(0)
  workspace.cli(['answer', 'set', '--key', 'live_answer', '--value', 'Realtime value'])
  await expect(page.getByRole('cell', { name: 'Realtime value', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'View live_answer' }).click()
  const existing = page.getByRole('region', { name: 'Edit answer' })
  await existing.getByRole('textbox', { name: 'Answer', exact: true }).fill('Unsaved value')
  await page.keyboard.press('Escape')
  await expect(existing).toHaveCount(0)
  expect(workspace.query("SELECT value FROM applicant_answers WHERE key = 'live_answer'")[0]?.value).toBe('Realtime value')
})

