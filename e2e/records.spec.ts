import { test, expect } from './fixtures'
import { panel, closeDialog, jobMenu, openJob } from './ui'

test.describe('saved records', () => {
  test.use({ populated: true })
  test('Jobs: search, details, archive/restore, failed mutations and protected deletion', async ({ workspace, page }) => {
    await workspace.go('Jobs')
    // 17 roles fit one page of cards, so no page numbers are shown.
    await expect(page.getByText('· 17 roles', { exact: true })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'pagination' })).toHaveCount(0)
    const search = page.getByRole('searchbox', { name: 'Search opportunities' })
    await search.fill('no such role')
    await expect(page.getByRole('heading', { name: 'No matching roles' })).toBeVisible()
    await search.fill('Engineer 01')
    await expect(page.getByText('· 1 of 17 roles', { exact: true })).toBeVisible()
    await workspace.fault('jobs/archive')
    await jobMenu(page, 'Engineer 01', 'Archive')
    await expect(page.getByRole('alert')).toContainText('Synthetic transport failure')
    expect(workspace.query('SELECT archived_at FROM jobs WHERE id=1')[0]?.archived_at).toBeNull()
    await jobMenu(page, 'Engineer 01', 'Archive')
    await page.getByRole('tab', { name: 'Archived (1)' }).click()
    await openJob(page, 'Engineer 01')
    await expect(page.getByRole('dialog').getByRole('button', { name: 'View application', exact: true })).toBeDisabled()
    await page.getByRole('dialog').getByRole('button', { name: 'View job' }).click()
    expect(await workspace.external()).toContain('https://example.com/jobs/1')
    await closeDialog(page)
    await jobMenu(page, 'Engineer 01', 'Restore')
    await page.getByRole('tab', { name: 'New (17)' }).click()
    await search.fill('Engineer 01')
    await jobMenu(page, 'Engineer 01', 'Delete')
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    expect(workspace.query('SELECT id FROM jobs WHERE id=1')).toHaveLength(1)
    await jobMenu(page, 'Engineer 01', 'Delete')
    await page.getByRole('button', { name: 'Delete job', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('alert')).toBeVisible()
    await closeDialog(page)
    workspace.cli(['job', 'save', '--linkedin-id', 'disposable', '--title', 'Disposable role', '--company', 'Example'])
    await search.fill('Disposable role')
    await jobMenu(page, 'Disposable role', 'Delete')
    await page.getByRole('button', { name: 'Delete job', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(workspace.query("SELECT id FROM jobs WHERE linkedin_job_id='disposable'")).toHaveLength(0)
    await search.fill('Engineer 01')
    await openJob(page, 'Engineer 01')
    await page.getByRole('dialog').getByRole('button', { name: 'View application', exact: true }).click()
    await workspace.ready('Application')
    await expect(page).toHaveURL(/jobId=1/)
  })

  test('Recruiters / Outreach: preview before sync, details, funnel and agent handoffs', async ({ workspace, page }) => {
    await workspace.visit('/contacts?tab=people', 'Contacts')
    await page.getByRole('searchbox', { name: 'Search recruiters', exact: true }).fill('Alex Recruiter')
    await expect(page.getByRole('article')).toHaveCount(1)
    await page.getByRole('button', { name: 'View details of Alex Recruiter' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'View LinkedIn' }).click()
    expect(await workspace.external()).toContain('https://www.linkedin.com/in/alex-recruiter/')
    await closeDialog(page)
    await page.getByRole('button', { name: 'Preview connection sync' }).click()
    await expect(panel(page, 'Connection sync preview')).toContainText('Alex Recruiter · accepted')
    expect(workspace.query("SELECT status FROM recruiters WHERE username='alex-recruiter'")[0]?.status).toBe('pending')
    await page.getByRole('button', { name: 'Apply accepted connections' }).click()
    await expect(page.getByText('Sync complete. 1 connections updated.')).toBeVisible()
    expect(workspace.query("SELECT status FROM recruiters WHERE username='alex-recruiter'")[0]?.status).toBe('accepted')
    await page.getByRole('button', { name: 'Preview connection sync' }).click()
    await expect(page.getByRole('heading', { name: 'You’re up to date' })).toBeVisible()
    await page.getByRole('button', { name: 'Dismiss' }).click()
    await workspace.visit('/contacts?tab=follow-ups', 'Contacts')
    const due = page.getByRole('article', { name: 'Due Person' })
    await expect(due).toContainText('Withdraw invite')
    await expect(due).toContainText('Invite not accepted after 30 days')
    await expect(page.getByText('Cooldown Company')).toBeHidden()
    await page.getByText('Outreach health', { exact: true }).click()
    await expect(page.getByText('Cooldown Company')).toBeVisible()
    // The review runs in place, beside the due actions.
    await page.getByRole('button', { name: 'Review follow-ups', exact: true }).click()
    await expect(page.getByText('Synthetic agent is working. Synthetic workflow completed.', { exact: true })).toBeVisible()
    await expect(page.getByRole('dialog', { name: 'Agent task' })).toHaveCount(0)
    await workspace.visit('/contacts?tab=people', 'Contacts')
    await page.getByRole('button', { name: 'Find recruiters', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Agent task' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Find recruiters', exact: true })).toBeVisible()
  })

  test('Applications: zero scores, details, portal and preparation IDs', async ({ workspace, page }) => {
    await workspace.go('Applications')
    await page.getByLabel('Search Applications').fill('Engineer 01')
    const card = page.getByRole('article', { name: 'Engineer 01' })
    await expect(card.getByText('Match 0', { exact: true })).toBeVisible()
    await expect(card.getByRole('progressbar')).toHaveAttribute('aria-valuetext', 'Applied, step 1 of 4')
    await page.getByRole('button', { name: 'View details of Engineer 01' }).click()
    await page.getByRole('button', { name: 'Open portal' }).click()
    expect(await workspace.external()).toContain('https://example.com/jobs/1')
    await page.getByRole('dialog').getByRole('button', { name: 'Prepare application' }).click()
    await workspace.ready('Application')
    await expect(page).toHaveURL(/jobId=1&applicationId=1/)
  })

  test('Interviews / Dashboard: upcoming excludes closed/past, detail search and realtime records', async ({ workspace, page }) => {
    await workspace.go('Interviews')
    await expect(page.getByRole('region', { name: 'Next conversation' })).toContainText('Future Company')
    await page.getByRole('button', { name: 'View details of Future Company' }).click()
    await expect(page.getByRole('dialog')).toContainText('Practice React')
    await closeDialog(page)
    await expect(page.getByRole('article', { name: 'Past Company' })).toHaveCount(0)
    await page.getByRole('tab', { name: /^Closed/ }).click()
    await expect(page.getByRole('article', { name: 'Past Company' })).toContainText('Closed')
    await page.getByRole('tab', { name: /^Upcoming/ }).click()
    // Added by hand through the interviews endpoint, then completed from its menu.
    await page.getByRole('button', { name: 'Add interview', exact: true }).click()
    const form = page.getByRole('dialog', { name: 'Add interview' })
    await form.getByLabel('Company').fill('Manual Company')
    await form.getByLabel('What to remember').fill('Bring questions')
    await form.getByRole('button', { name: 'Save interview' }).click()
    await expect(form).toHaveCount(0)
    await expect(page.getByRole('article', { name: 'Manual Company' })).toContainText('Bring questions')
    expect(workspace.query("SELECT stage, status, notes FROM interviews WHERE company = 'Manual Company'")).toEqual([{ stage: 'technical', status: 'scheduled', notes: 'Bring questions' }])
    await page.getByRole('button', { name: 'More actions for Manual Company' }).click()
    await page.getByRole('menuitem', { name: 'Mark as done' }).click()
    await expect(page.getByRole('article', { name: 'Manual Company' })).toHaveCount(0)
    expect(workspace.query("SELECT status FROM interviews WHERE company = 'Manual Company'")).toEqual([{ status: 'done' }])
    await workspace.go('Dashboard')
    await expect(panel(page, 'Coming up')).toContainText('Future Company')
    await expect(panel(page, 'Coming up')).not.toContainText('Past Company')
    workspace.cli(['interview', 'add', '--company', 'Live Interview', '--when', new Date(Date.now() + 86400_000).toISOString(), '--stage', 'technical'])
    await expect(panel(page, 'Coming up')).toContainText('Live Interview')
    await panel(page, 'Coming up').getByRole('link', { name: 'View all' }).click()
    await workspace.ready('Interviews')
    await expect(page.getByRole('article', { name: 'Live Interview' })).toBeVisible()
  })

  test('Activity: pagination resets with search and receives CLI events', async ({ workspace, page }) => {
    await workspace.visit('/launch?tab=history', 'Agent')
    await page.getByRole('button', { name: 'Next', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Page 2', exact: true })).toHaveAttribute('aria-current', 'page')
    await page.getByLabel('Search Activity').fill('Seed activity 17')
    await expect(page.getByRole('cell', { name: 'Seed activity 17', exact: true })).toBeVisible()
    // One page left: the page numbers are hidden.
    await expect(page.getByRole('navigation', { name: 'pagination' })).toHaveCount(0)
    workspace.cli(['activity', 'log', '--summary', 'Live activity', '--skill', 'synthetic'])
    await page.getByLabel('Search Activity').fill('Live activity')
    await expect(page.getByRole('cell', { name: 'Live activity', exact: true })).toBeVisible()
    await page.reload()
    await workspace.ready('Agent')
    await page.getByLabel('Search Activity').fill('Live activity')
    await expect(page.getByRole('cell', { name: 'Live activity', exact: true })).toBeVisible()
  })
})
