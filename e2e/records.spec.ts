import { test, expect } from './fixtures'
import { choose, panel, closeDialog } from './ui'

test.describe('saved records', () => {
  test.use({ populated: true })
  test('Jobs: pagination, filters, details, archive/restore, failed mutations and protected deletion', async ({ workspace, page }) => {
    await workspace.go('Jobs')
    await expect(page.getByText('17 results · Page 1 of 2')).toBeVisible()
    await panel(page, 'Opportunities').getByRole('button', { name: 'Next', exact: true }).click()
    await expect(page.getByText('17 results · Page 2 of 2')).toBeVisible()
    await page.getByLabel('Search Opportunities', { exact: true }).fill('Engineer 01')
    await expect(page.getByText('1 results · Page 1 of 1')).toBeVisible()
    await choose(page, 'Filter by status', 'assessed')
    await expect(page.getByRole('heading', { name: 'No matching results' })).toBeVisible()
    await choose(page, 'Filter by status', 'All statuses')
    await workspace.fault('jobs/archive')
    await page.getByRole('button', { name: 'Archive Engineer 01', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Synthetic transport failure')
    expect(workspace.query('SELECT archived_at FROM jobs WHERE id=1')[0]?.archived_at).toBeNull()
    await page.getByRole('button', { name: 'Archive Engineer 01', exact: true }).click()
    await page.getByRole('tab', { name: 'Archived (1)' }).click()
    await page.getByRole('button', { name: 'View Engineer 01', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('button', { name: 'Prepare application' })).toBeDisabled()
    await page.getByRole('dialog').getByRole('button', { name: 'View opportunity' }).click()
    expect(await workspace.external()).toContain('https://example.com/jobs/1')
    await closeDialog(page)
    await page.getByRole('button', { name: 'Restore Engineer 01', exact: true }).click()
    await page.getByRole('tab', { name: 'Active (17)' }).click()
    await page.getByLabel('Search Opportunities', { exact: true }).fill('Engineer 01')
    await page.getByRole('button', { name: 'Delete Engineer 01', exact: true }).click()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    expect(workspace.query('SELECT id FROM jobs WHERE id=1')).toHaveLength(1)
    await page.getByRole('button', { name: 'Delete Engineer 01', exact: true }).click()
    await page.getByRole('button', { name: 'Delete job', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('alert')).toBeVisible()
    await closeDialog(page)
    workspace.cli(['job', 'save', '--linkedin-id', 'disposable', '--title', 'Disposable role', '--company', 'Example'])
    await page.getByLabel('Search Opportunities', { exact: true }).fill('Disposable role')
    await page.getByRole('button', { name: 'Delete Disposable role', exact: true }).click()
    await page.getByRole('button', { name: 'Delete job', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(workspace.query("SELECT id FROM jobs WHERE linkedin_job_id='disposable'")).toHaveLength(0)
    await page.getByLabel('Search Opportunities', { exact: true }).fill('Engineer 01')
    await page.getByRole('button', { name: 'Prepare application', exact: true }).click()
    await workspace.ready('Apply')
    await expect(page).toHaveURL(/jobId=1/)
  })

  test('Recruiters / Outreach: preview before sync, details, funnel and agent handoffs', async ({ workspace, page }) => {
    await workspace.go('Recruiters')
    await page.getByLabel('Search Recruiters', { exact: true }).fill('Alex Recruiter')
    await page.getByRole('button', { name: 'View Alex Recruiter' }).click()
    await page.getByRole('button', { name: 'View LinkedIn' }).click()
    expect(await workspace.external()).toContain('https://www.linkedin.com/in/alex-recruiter/')
    await closeDialog(page)
    await page.getByRole('button', { name: 'Preview connection sync' }).click()
    await expect(panel(page, 'Connection sync preview')).toContainText('Alex Recruiter · accepted')
    expect(workspace.query("SELECT status FROM recruiters WHERE username='alex-recruiter'")[0]?.status).toBe('pending')
    await page.getByRole('button', { name: 'Apply accepted connections' }).click()
    await expect(page.getByText('Sync complete. 1 connections updated.')).toBeVisible()
    expect(workspace.query("SELECT status FROM recruiters WHERE username='alex-recruiter'")[0]?.status).toBe('accepted')
    await page.getByRole('button', { name: 'Preview connection sync' }).click()
    await expect(page.getByRole('heading', { name: 'You’re up to date' })).toBeVisible()
    await page.getByRole('button', { name: 'Dismiss' }).click()
    await workspace.go('Outreach')
    await expect(panel(page, 'Next actions')).toContainText('Due Person')
    await expect(panel(page, 'Companies in cooldown')).toContainText('Cooldown Company')
    await page.getByLabel('Search Next actions').fill('no match')
    await expect(panel(page, 'Next actions').getByRole('heading', { name: 'No matching results' })).toBeVisible()
    await page.getByRole('button', { name: 'Review next actions' }).click()
    await workspace.ready('Launch')
    await expect(page.getByRole('combobox', { name: /^Skill/ })).toContainText('Review follow-ups')
    await page.getByRole('button', { name: 'Run agent' }).click()
    await expect(page.getByText('Synthetic agent is working. Synthetic workflow completed.', { exact: true })).toBeVisible()
    await workspace.go('Recruiters')
    await page.getByRole('button', { name: 'Find recruiters', exact: true }).click()
    await workspace.ready('Launch')
    await expect(page.getByRole('combobox', { name: /^Skill/ })).toContainText('Find recruiters')
  })

  test('Applications: zero scores, details, portal and preparation IDs', async ({ workspace, page }) => {
    await workspace.go('Automatic applications')
    await page.getByLabel('Search Automatic applications').fill('Engineer 01')
    await expect(page.getByRole('cell', { name: '0%', exact: true })).toBeVisible()
    await expect(page.getByRole('cell', { name: 'draft', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'View Engineer 01' }).click()
    await page.getByRole('button', { name: 'Open portal' }).click()
    expect(await workspace.external()).toContain('https://example.com/jobs/1')
    await page.getByRole('dialog').getByRole('button', { name: 'Prepare application' }).click()
    await workspace.ready('Apply')
    await expect(page).toHaveURL(/jobId=1&applicationId=1/)
  })

  test('Interviews / Dashboard: upcoming excludes closed/past, detail search and realtime records', async ({ workspace, page }) => {
    await workspace.go('Interviews')
    await page.getByRole('button', { name: 'View Future Company' }).click()
    await expect(page.getByRole('dialog')).toContainText('Practice React')
    await closeDialog(page)
    await page.getByLabel('Search Interviews').fill('Past Company')
    await expect(page.getByRole('cell', { name: 'closed', exact: true })).toBeVisible()
    await workspace.go('Dashboard')
    await expect(panel(page, 'Coming up')).toContainText('Future Company')
    await expect(panel(page, 'Coming up')).not.toContainText('Past Company')
    workspace.cli(['interview', 'add', '--company', 'Live Interview', '--when', new Date(Date.now() + 86400_000).toISOString(), '--stage', 'technical'])
    await expect(panel(page, 'Coming up')).toContainText('Live Interview')
    await panel(page, 'Coming up').getByRole('link', { name: 'View all' }).click()
    await workspace.ready('Interviews')
    await expect(page.getByRole('button', { name: 'View Live Interview' })).toBeVisible()
  })

  test('Activity: pagination resets with search and receives CLI events', async ({ workspace, page }) => {
    await workspace.go('Activity')
    await page.getByRole('button', { name: 'Next', exact: true }).click()
    await expect(page.getByText('17 results · Page 2 of 2')).toBeVisible()
    await page.getByLabel('Search Activity').fill('Seed activity 17')
    await expect(page.getByText('1 results · Page 1 of 1')).toBeVisible()
    workspace.cli(['activity', 'log', '--summary', 'Live activity', '--skill', 'synthetic'])
    await page.getByLabel('Search Activity').fill('Live activity')
    await expect(page.getByRole('cell', { name: 'Live activity', exact: true })).toBeVisible()
    await page.reload()
    await workspace.ready('Activity')
    await page.getByLabel('Search Activity').fill('Live activity')
    await expect(page.getByRole('cell', { name: 'Live activity', exact: true })).toBeVisible()
  })
})
