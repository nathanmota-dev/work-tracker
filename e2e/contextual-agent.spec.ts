import { test, expect } from './fixtures'

test('Contextual agent survives navigation and completes a permission-gated search', async ({ workspace, page }) => {
  workspace.setScenario({ agent: 'permission' })
  await workspace.go('Dashboard')
  await page.getByRole('link', { name: 'Discover opportunities', exact: true }).click()
  await expect(page.getByLabel('Roles')).toBeFocused()
  await page.getByLabel('Roles').fill('React')
  await page.getByLabel('Location', { exact: true }).fill('Remote')
  await page.getByLabel('Additional context').fill('Junior roles only')
  // Finding jobs starts at once, in place.
  await page.getByRole('button', { name: 'Find jobs with agent' }).click()
  const panel = page.getByRole('dialog', { name: 'Agent task' })
  await expect(page.getByRole('heading', { name: 'Discover opportunities', exact: true, level: 1 })).toBeVisible()
  const permission = page.getByRole('dialog', { name: 'Agent tool permission' })
  await expect(permission).toBeVisible()
  await permission.getByRole('button', { name: 'Decide later' }).click()
  await workspace.go('Jobs')
  await workspace.go('Profile')
  await expect(page.getByRole('button', { name: 'Open agent task' })).toContainText('Waiting')
  await page.getByRole('button', { name: 'Open agent task' }).click()
  await expect(panel.getByRole('log')).toContainText('Discover opportunities')
  await panel.getByRole('button', { name: /Review permission:/ }).click()
  await permission.getByRole('button', { name: 'Allow once' }).click()
  // The fake agent asks for the same tool twice.
  await expect(permission).toBeVisible()
  await permission.getByRole('button', { name: 'Allow once' }).click()
  await expect(panel.getByRole('log')).toContainText('Synthetic workflow completed.')
  await panel.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('link', { name: 'View new jobs', exact: true }).click()
  await workspace.ready('Jobs')
  await expect(page.getByRole('article', { name: 'React Engineer', exact: true })).toBeVisible()
  expect(workspace.calls('prompt')).toHaveLength(1)
})
