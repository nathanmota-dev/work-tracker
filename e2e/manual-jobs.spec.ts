import { test, expect } from './fixtures'
import { panel } from './ui'

test('Jobs: create, correct a failed save, deduplicate, edit and prepare an external role', async ({ workspace, page }) => {
  test.setTimeout(120_000)
  await workspace.go('Jobs')
  await page.getByRole('button', { name: 'Add job', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Add job' })
  await dialog.getByLabel('Role title').fill('External Engineer')
  await dialog.getByLabel('Company name').fill('Synthetic Corp')
  await expect(dialog.getByText('Missing for preparation: job link, job description.')).toBeVisible()
  await dialog.getByLabel('Job link').fill('https://careers.example/jobs?jobId=42')
  await dialog.getByLabel('Source', { exact: true }).fill('careers')
  await dialog.getByLabel('Source job ID').fill('42')
  await workspace.fault('jobs/create')
  await dialog.getByRole('button', { name: 'Save job' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Synthetic transport failure')
  expect(workspace.query('SELECT * FROM jobs')).toHaveLength(0)
  await dialog.getByRole('button', { name: 'Save job' }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Edit job' })).toBeVisible()
  const id = workspace.query('SELECT id FROM jobs')[0]!.id
  await page.getByRole('button', { name: 'Edit job' }).click()
  dialog = page.getByRole('dialog', { name: 'Edit job' })
  await expect(dialog.getByLabel('Role title')).toHaveValue('External Engineer')
  await dialog.getByLabel('Job description').fill('Build synthetic React systems.')
  await dialog.getByRole('button', { name: 'Save job' }).click()
  await expect(page.getByText('Job saved.', { exact: true })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: 'Add job', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Add job' })
  await dialog.getByLabel('Role title').fill('External Engineer')
  await dialog.getByLabel('Company name').fill('Synthetic Corp')
  await dialog.getByLabel('Job link').fill('http://www.careers.example/jobs/?utm_source=test&jobId=42#top')
  await dialog.getByRole('button', { name: 'Save job' }).click()
  await expect(page.getByText(`Job #${id} already exists. Its saved content was preserved.`)).toBeVisible()
  expect(workspace.query('SELECT * FROM jobs')).toHaveLength(1)
  expect(workspace.calls('prompt')).toHaveLength(0)
  expect(workspace.calls('mcp')).toHaveLength(0)
  await page.getByRole('dialog').getByRole('button', { name: 'Prepare application' }).click()
  await workspace.ready('Apply')
  await page.getByLabel('Additional context').fill('Synthetic context before the first application')
  await page.getByRole('button', { name: 'Generate resume', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Fill application', exact: true })).toBeEnabled({ timeout: 90_000 })
  await expect(panel(page, 'Tailored PDF').locator('.react-pdf__Page__textContent')).toContainText('Tailored resume.')
  const application = workspace.query('SELECT id, job_id, resume_path FROM applications')[0]!
  expect(application.job_id).toBe(id)
  await workspace.go('Jobs')
  await expect(page.getByRole('dialog')).toContainText('External Engineer')
  await page.getByRole('button', { name: 'Edit job' }).click()
  await page.getByLabel('Role title').fill('Updated Engineer')
  await page.getByRole('button', { name: 'Save job' }).click()
  await expect(page.getByRole('dialog').getByRole('heading', { name: 'Updated Engineer' })).toBeVisible()
  expect(workspace.query('SELECT id, job_id, resume_path FROM applications')).toEqual([application])
  await page.getByRole('dialog').getByRole('button', { name: 'Fill in Apply', exact: true }).click()
  await workspace.ready('Apply')
  await expect(page.getByLabel('Additional context')).toHaveValue('Synthetic context before the first application')
})
