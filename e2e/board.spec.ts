import { test, expect } from './fixtures'
import { choose, closeDialog } from './ui'
import type { Page } from '@playwright/test'

async function create(page: Page, company = 'Board Company') {
  await page.getByRole('button', { name: 'New application', exact: true }).first().click()
  await expect(page.getByRole('button', { name: 'Save application' })).toBeDisabled()
  await page.getByLabel('Company name', { exact: true }).fill(company)
  await page.getByLabel('Job link', { exact: true }).fill('https://example.com/board-job')
  await page.getByRole('button', { name: 'Save application' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

test('Board: minimal registration, failed edits, optional fields, stages, timeline and persistence', async ({ workspace, page }) => {
  await workspace.board()
  await create(page)
  await page.getByRole('button', { name: 'Edit Board Company application' }).click()
  await page.getByLabel('Role title').fill('Full stack engineer')
  await choose(page, 'Role type', 'Full-stack')
  await page.getByLabel('Stack', { exact: true }).fill('React, TypeScript')
  await page.getByLabel('Compensation').fill('USD 100k')
  await page.getByLabel('Notes').fill('Synthetic note')
  await workspace.fault('application-board/update')
  await page.getByRole('button', { name: 'Save application', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Synthetic transport failure')
  await expect(page.getByLabel('Notes')).toHaveValue('Synthetic note')
  await page.getByRole('button', { name: 'Save application', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByLabel('Search applications').fill('typescript')
  await expect(page.getByRole('button', { name: 'View Board Company application' })).toBeVisible()
  await page.getByLabel('Search applications').fill('nonexistent')
  await expect(page.getByText('No applications match your search.')).toBeVisible()
  await page.getByLabel('Search applications').fill('')
  await page.getByRole('button', { name: 'View Board Company application' }).click()
  await choose(page, 'Current stage', 'Technical interview')
  await expect.poll(() => workspace.query('SELECT current_stage_id FROM applications')[0]?.current_stage_id).toBe(3)
  await expect(page.getByRole('dialog')).toContainText('Technical interview')
  await expect.poll(() => workspace.query("SELECT id FROM application_events WHERE event_type='moved'").length).toBe(1)
  await workspace.fault('application-board/move')
  await choose(page, 'Current stage', 'Offer')
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Synthetic transport failure')
  expect(workspace.query('SELECT current_stage_id FROM applications')[0]?.current_stage_id).toBe(3)
  await closeDialog(page)
  await page.getByRole('button', { name: 'Manage stages' }).click()
  await expect(page.getByRole('button', { name: 'Hide Applied', exact: true })).toBeDisabled()
  await page.getByLabel('New stage name').fill('Coding exercise')
  await choose(page, 'Stage category', 'Assessment')
  await page.getByRole('button', { name: 'Add stage' }).click()
  await expect(page.getByLabel('Name for Coding exercise')).toBeVisible()
  await page.getByRole('button', { name: 'Move Coding exercise up' }).click()
  await page.getByLabel('Name for Coding exercise').fill('Pair programming')
  await page.getByRole('button', { name: 'Save Coding exercise name' }).click()
  await expect(page.getByLabel('Name for Pair programming')).toHaveValue('Pair programming')
  await page.getByRole('button', { name: 'Hide Pair programming' }).click()
  await page.getByRole('button', { name: 'Restore Pair programming' }).click()
  await page.getByRole('button', { name: 'Hide Technical interview' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await workspace.restart()
  await workspace.board()
  await expect(workspace.page.getByLabel('Technical interview applications').getByRole('button', { name: 'View Board Company application' })).toBeVisible()
  expect(workspace.query('SELECT notes, stack_json FROM applications')[0]).toMatchObject({ notes: 'Synthetic note', stack_json: '["React","TypeScript"]' })
})

for (const outcome of ['Rejected', 'Withdrawn', 'No response', 'Hired']) {
  test(`Board: archive with ${outcome}, preserve history and reopen`, async ({ workspace, page }) => {
    await workspace.board()
    await create(page)
    await page.getByRole('button', { name: 'Archive Board Company application' }).click()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    expect(workspace.query('SELECT tracking_status FROM applications')[0]?.tracking_status).toBe('active')
    await page.getByRole('button', { name: 'Archive Board Company application' }).click()
    await choose(page, 'Outcome', outcome)
    await page.getByLabel('Closing note').fill('Synthetic closing note')
    await page.getByRole('button', { name: 'Archive application', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('tab', { name: 'Archived (1)' }).click()
    await expect(page.getByText(outcome, { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'View Board Company application' }).click()
    await expect(page.getByRole('dialog')).toContainText('Synthetic closing note')
    await page.getByRole('button', { name: 'Reopen application', exact: true }).last().click()
    await closeDialog(page)
    await page.getByRole('tab', { name: 'Active (1)' }).click()
    await expect(page.getByRole('button', { name: 'View Board Company application' })).toBeVisible()
    expect(workspace.query('SELECT event_type FROM application_events').map(row => row.event_type)).toEqual(['created', 'archived', 'reopened'])
  })
}

test('Board: real pointer drag changes stage and dropping in archive requires confirmation', async ({ workspace, page }) => {
  await workspace.resize(1400, 1000)
  await workspace.board()
  await create(page)
  const handle = page.getByRole('button', { name: 'Drag Board Company application' })
  const target = page.getByLabel('Recruiter interview applications')
  await handle.scrollIntoViewIfNeeded()
  const sourceBox = (await handle.boundingBox())!
  const targetBox = (await target.boundingBox())!
  await page.mouse.move(sourceBox.x + sourceBox.width / 2, sourceBox.y + sourceBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(sourceBox.x + 20, sourceBox.y + 20, { steps: 5 })
  await page.mouse.move(targetBox.x + targetBox.width / 2, targetBox.y + 80, { steps: 20 })
  await page.mouse.up()
  await expect(target.getByRole('button', { name: 'View Board Company application' })).toBeVisible()
  expect(workspace.query('SELECT current_stage_id FROM applications')[0]?.current_stage_id).toBe(2)
  await expect(handle).toBeEnabled()
  await expect(page.locator('[data-slot="card"][aria-hidden]')).toHaveCount(0)
  await page.getByLabel('Archive applications', { exact: true }).scrollIntoViewIfNeeded()
  await handle.hover()
  const moved = (await handle.boundingBox())!
  const archive = (await page.getByLabel('Archive applications', { exact: true }).boundingBox())!
  await page.mouse.move(moved.x + moved.width / 2, moved.y + moved.height / 2)
  await page.mouse.down()
  await page.mouse.move(moved.x + moved.width / 2 + 40, moved.y + moved.height / 2, { steps: 10 })
  await expect(page.locator('[aria-busy]').filter({ has: handle })).toHaveClass(/opacity-40/)
  await page.mouse.move(archive.x + archive.width / 2, archive.y + archive.height / 2, { steps: 20 })
  await page.mouse.up()
  await expect(page.getByRole('dialog', { name: 'Archive Board Company' })).toBeVisible()
  expect(workspace.query('SELECT tracking_status FROM applications')[0]?.tracking_status).toBe('active')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
})
