import { test, expect } from './fixtures'
import { choose } from './ui'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

test('Integrations: validated saves, hidden values, independent sessions and Apply corrections', async ({ workspace, page }) => {
  workspace.seed()
  // Agents are configured and tested in Agent › Setup.
  await workspace.go('Agent')
  await expect(page.getByRole('combobox', { name: /^Agent(?:$|\s)/ })).toContainText('opencode ACP')
  await expect(page.getByLabel('Arguments (JSON array)')).toHaveValue(/stored argument 1/)
  await page.getByLabel('Arguments (JSON array)').fill('[1]')
  await page.getByRole('button', { name: 'Save integration' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByText('Integration saved.', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Reload settings' }).click()
  await page.getByLabel('Executable command').fill('missing-integration-fixture')
  await page.getByRole('button', { name: 'Save integration' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Integration saved.' })).toBeVisible()
  await page.getByRole('button', { name: 'Test agent' }).click()
  await expect(page.getByLabel('Diagnostic results')).toContainText('missing_executable')
  await workspace.visit('/apply?jobId=1', 'Application')
  await expect(page.getByRole('button', { name: 'Generate resume', exact: true })).toBeDisabled()
  await page.getByRole('link', { name: 'Configure opencode ACP' }).first().click()
  await expect(page.getByRole('heading', { name: 'Agent connection', exact: true })).toBeVisible()
  await page.getByLabel('Executable command').fill(process.execPath)
  await page.getByRole('button', { name: 'Save integration' }).click()
  await page.getByLabel('Model to test (empty uses provider default)').fill('invalid-fixture-model')
  await page.getByRole('button', { name: 'Test agent' }).click()
  await expect(page.getByLabel('Diagnostic results')).toContainText('invalid_model')
  await page.getByLabel('Model to test (empty uses provider default)').fill('')
  await page.getByRole('button', { name: 'Test agent' }).click()
  await expect(page.getByLabel('Diagnostic results')).toContainText('Using the provider default model')
  // MCP servers stay in Settings › Integrations.
  await workspace.visit('/settings?section=integrations', 'Settings')
  await expect(page.getByRole('combobox', { name: /^Integration/ })).toContainText('Chrome MCP')
  await page.getByRole('button', { name: 'Test saved integration' }).click()
  await expect(page.getByLabel('Diagnostic results')).toContainText('does not verify LinkedIn authentication')
  workspace.setScenario({ mcp: 'login' })
  await choose(page, 'Integration', 'LinkedIn MCP')
  await page.getByRole('button', { name: 'Test saved integration' }).click()
  await expect(page.getByLabel('Diagnostic results')).toContainText('authentication_required')
  await expect(page.locator('body')).not.toContainText('synthetic-secret')
  workspace.setScenario({})
  await page.getByRole('button', { name: 'Test saved integration' }).click()
  await expect(page.getByLabel('Diagnostic results')).toContainText('separate LinkedIn session answered')
  await workspace.visit('/apply?jobId=1', 'Application')
  await page.getByRole('button', { name: 'Test availability again' }).click()
  await expect(page.getByRole('button', { name: 'Generate resume', exact: true })).toBeEnabled()
  expect(workspace.query('SELECT id FROM application_runs')).toEqual([])
  const config = JSON.parse(readFileSync(join(workspace.home, 'config.json'), 'utf8'))
  expect(config.acp.opencode.args).toEqual([expect.stringContaining('protocol.cjs')])
  expect(config.acp['claude-code'].env.E2E_PROVIDER).toBe('claude-code')
})
