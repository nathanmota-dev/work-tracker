import { test, expect } from './fixtures'
import { appendFileSync, copyFileSync, existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { panel } from './ui'

test('Profile sources: the base resume is generated from the profile, a LinkedIn export replaces the resume data and tailoring reads it', async ({ workspace, page }) => {
  test.setTimeout(180_000)

  // The base resume is generated from the resume data: its LaTeX is read-only and its PDF is compiled on opening.
  await workspace.visit('/resume?id=base', 'Base resume')
  await expect(page.getByText(/Built from/)).toContainText('Built from resume-data.json (resume data).')
  // The editor renders only its visible lines: the body is checked in the generated file.
  const code = page.getByRole('textbox', { name: 'resume.tex (read-only)' })
  await expect(code).toContainText('Generated by Work Tracker from your profile.')
  await expect(code).toHaveAttribute('aria-readonly', 'true')
  const generated = () => existsSync(workspace.baseResume) ? readFileSync(workspace.baseResume, 'utf8') : ''
  await expect.poll(generated).toContain('Synthetic Company 1')
  await expect(page.getByLabel('LaTeX project folder')).toHaveCount(0)
  await expect(panel(page, 'Base resume PDF').locator('.react-pdf__Page__canvas').first()).toBeVisible({ timeout: 90_000 })

  // The LinkedIn export replaces the resume data only after a confirmation.
  await workspace.go('Profile')
  const openImport = async () => {
    await page.getByRole('button', { name: 'Import resume', exact: true }).first().click()
    return page.getByRole('dialog', { name: 'Resume files' })
  }
  let sheet = await openImport()
  await sheet.getByLabel('Choose profile files').setInputFiles('src/test/fixtures/profile/linkedin-export.pdf')
  const replace = sheet.getByRole('alertdialog', { name: 'Replace profile source' })
  await expect(replace).toBeVisible({ timeout: 30_000 })
  await expect(sheet.getByRole('region', { name: 'Upload progress' }).getByRole('listitem').filter({ hasText: 'linkedin-export.pdf' })).toContainText('Your profile is built from resume-data.json. Replace it with this file?')
  expect(existsSync(join(workspace.profileDir, 'linkedin-export.pdf'))).toBe(false)
  await replace.getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(sheet.getByRole('region', { name: 'Upload progress' }).getByRole('listitem').filter({ hasText: 'linkedin-export.pdf' })).toContainText('Uploaded', { timeout: 30_000 })
  expect(existsSync(workspace.dataFile)).toBe(false)
  let files = sheet.getByRole('list', { name: 'Profile files' })
  await expect(files.getByRole('listitem')).toHaveCount(1)
  await expect(files.getByRole('listitem').filter({ hasText: 'linkedin-export.pdf' })).toContainText('LinkedIn exportProfile source')
  await page.keyboard.press('Escape')
  await expect(sheet).toHaveCount(0)

  // Details the resume data had filled follow the new source.
  const personal = page.getByRole('region', { name: 'Personal details' })
  await expect(personal.getByRole('button', { name: 'Edit Email', exact: true })).toHaveAttribute('title', 'alex@example.com · From LinkedIn')
  await expect(personal.getByRole('button', { name: 'Edit LinkedIn profile', exact: true })).toContainText('https://www.linkedin.com/in/alex-ex/')
  await expect(page.getByRole('list', { name: 'Skills' })).toContainText('PostgreSQL')
  expect(workspace.query("SELECT key, source FROM answer_autofill ORDER BY key")).toEqual(
    ['city', 'country', 'email', 'first_name', 'full_name', 'languages', 'last_name', 'linkedin_url', 'location', 'summary'].map(key => ({ key, source: 'linkedin' })))

  // A PDF placed in the folder by hand is imported without any action; a second export is reference text only.
  sheet = await openImport()
  files = sheet.getByRole('list', { name: 'Profile files' })
  const placed = join(workspace.profileDir, 'placed-by-hand.pdf')
  copyFileSync('src/test/fixtures/profile/linkedin-export.pdf', placed)
  appendFileSync(placed, '\n%placed\n')
  await expect(files.getByRole('listitem').filter({ hasText: 'placed-by-hand.pdf' })).toContainText('Reference', { timeout: 30_000 })
  await expect(sheet.getByText('placed-by-hand.pdf is a LinkedIn export, but linkedin-export.pdf is your profile; the export is used as reference text only.')).toBeVisible()
  await page.keyboard.press('Escape')

  // The base resume is now generated from the export.
  await workspace.visit('/resume?id=base', 'Base resume')
  await expect(page.getByText(/Built from/)).toContainText('Built from linkedin-export.pdf (LinkedIn export).')
  await expect(page.getByRole('textbox', { name: 'resume.tex (read-only)' })).toContainText('Generated by Work Tracker from your profile.')
  await expect.poll(generated).toContain('Alex Example')
  expect(generated()).not.toContain('Synthetic Company 1')

  // Tailoring reads the export in the resume data's shape, with the other PDF as a reference.
  workspace.cli(['job', 'save', '--linkedin-id', '9301', '--title', 'TypeScript Engineer', '--company', 'Example Company', '--link', 'https://example.com/jobs/9301', '--description', 'TypeScript and React'])
  const id = workspace.query("SELECT id FROM jobs WHERE linkedin_job_id = '9301'")[0]!.id
  await page.evaluate(jobId => { window.location.hash = `/apply?jobId=${jobId}` }, id)
  await workspace.ready('Application')
  await page.getByRole('button', { name: 'Generate resume', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Approve this version', exact: true })).toBeEnabled({ timeout: 90_000 })
  const profile = workspace.calls('tailor').at(-1)!.profile as { name: string; skills: string[]; work: { company: string }[]; profileSources: { references: { file: string }[] } }
  expect(profile.name).toBe('Alex Example')
  expect(profile.skills).toEqual(['TypeScript', 'React', 'PostgreSQL'])
  expect(profile.work.map(role => role.company)).toEqual(['Northwind Labs', 'Northwind Labs', 'Contoso Analytics', 'Fabrikam Studio'])
  expect(profile.profileSources.references.map(reference => reference.file)).toEqual(['placed-by-hand.pdf'])
})
