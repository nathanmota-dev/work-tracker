import { test, expect } from './fixtures'
import { choose, panel } from './ui'

test('Review center: select five jobs, recover a failure, adjust, restart, review, fill and confirm each submission', async ({ workspace }) => {
  test.setTimeout(300_000)
  for (let i = 1; i <= 5; i++) workspace.cli(['job', 'save', '--linkedin-id', String(9900 + i), '--title', `Review role ${i}`, '--company', `Synthetic review ${i}`, '--link', `https://example.test/review/${i}`])
  workspace.setScenario({ agent: 'error' })
  await workspace.go('Jobs')
  await workspace.page.getByRole('button', { name: 'Select all filtered results (5)', exact: true }).click()
  await workspace.page.getByRole('button', { name: 'Prepare selected', exact: true }).click()
  await choose(workspace.page, 'Batch agent', 'opencode')
  await workspace.page.getByRole('button', { name: 'Create batch (5)', exact: true }).click()
  await workspace.page.getByRole('link', { name: 'Review batch', exact: true }).click()
  const summary = () => workspace.page.getByLabel('Batch results')
  const count = (name: string) => summary().locator('div').filter({ has: workspace.page.locator('dt', { hasText: new RegExp(`^${name}$`) }) }).locator('dd')
  await expect(count('failed')).toHaveText('5', { timeout: 90_000 })
  await expect(workspace.page.getByRole('region', { name: 'Selected batch item' })).toContainText('Synthetic agent failure')
  workspace.setScenario({})
  await workspace.page.getByRole('button', { name: 'Retry pending failures', exact: true }).click()
  await expect(count('prepared')).toHaveText('5', { timeout: 120_000 })
  expect(workspace.query('SELECT COUNT(*) AS n FROM applications')).toEqual([{ n: 5 }])
  expect(workspace.calls('fill')).toHaveLength(0)
  await workspace.resize(1400)
  await expect(panel(workspace.page, 'Tailored PDF').locator('.react-pdf__Page__textContent')).toContainText('Tailored resume.')
  const firstDocument = workspace.query('SELECT id, pdf_hash FROM document_versions ORDER BY rowid')[0]!
  // A transport failure keeps the request editable and the validated document intact.
  await workspace.page.getByRole('textbox', { name: 'Document adjustment' }).fill('Emphasize the existing React experience')
  await workspace.fault('preparation-batches/adjust')
  await workspace.page.getByRole('button', { name: 'Request adjustment', exact: true }).click()
  await expect(workspace.page.getByRole('alert')).toContainText('Synthetic transport failure')
  await expect(workspace.page.getByRole('textbox', { name: 'Document adjustment' })).toHaveValue('Emphasize the existing React experience')
  await workspace.page.getByRole('button', { name: 'Request adjustment', exact: true }).click()
  await expect(workspace.page.getByText('Requested adjustment: Emphasize the existing React experience', { exact: true })).toBeVisible()
  await expect(count('prepared')).toHaveText('5', { timeout: 90_000 })
  expect(workspace.query('SELECT id, pdf_hash FROM document_versions ORDER BY rowid')[0]).toEqual(firstDocument)
  expect(workspace.query('SELECT COUNT(*) AS n FROM document_versions')).toEqual([{ n: 6 }])
  await workspace.restart()
  await workspace.go('Apply')
  await workspace.page.getByRole('link', { name: 'Review batch', exact: true }).click()
  await expect(workspace.page.getByText('paused after restart', { exact: true })).toBeVisible()
  await expect(count('prepared')).toHaveText('5')
  await workspace.page.getByRole('link', { name: 'Show unfinished only', exact: true }).click()
  await workspace.page.getByRole('button', { name: 'Resume pending work', exact: true }).click()
  for (let position = 1; position <= 5; position++) {
    await workspace.page.getByRole('navigation', { name: 'Batch items' }).getByRole('link', { name: new RegExp(`^${position}\\. `) }).click()
    await expect(workspace.page.getByRole('region', { name: 'Selected batch item' })).toContainText(`Item ${position} of 5`)
    await workspace.page.getByRole('button', { name: 'Approve this version', exact: true }).click()
    await expect(workspace.page.getByRole('button', { name: 'I submitted in the browser', exact: true })).toBeVisible({ timeout: 60_000 })
    await expect(workspace.page.getByRole('list', { name: 'Fill checklist' })).toContainText('Gender')
    for (const label of ['Phone', 'Gender']) await workspace.page.getByRole('checkbox', { name: `Completed ${label} in the portal` }).check()
    expect(workspace.query("SELECT COUNT(*) AS n FROM applications WHERE submission_status = 'submitted'")).toEqual([{ n: position - 1 }])
    if (position === 1) {
      await workspace.fault('application-preparation/submitted')
      await workspace.page.getByRole('button', { name: 'I submitted in the browser', exact: true }).click()
      await expect(workspace.page.getByRole('alert')).toContainText('Synthetic transport failure')
      await expect(count('submitted')).toHaveText('0')
    }
    await workspace.page.getByRole('button', { name: 'I submitted in the browser', exact: true }).click()
    await expect(count('submitted')).toHaveText(String(position))
    await expect(workspace.page.getByRole('region', { name: 'Selected batch item' })).toContainText(`Item ${position} of 5`)
  }
  await expect(workspace.page.getByText('No unfinished items remain.', { exact: true })).toBeVisible()
  expect(workspace.query('SELECT COUNT(*) AS n FROM applications')).toEqual([{ n: 5 }])
  expect(workspace.calls('fill')).toHaveLength(5)
  expect(workspace.query('SELECT COUNT(*) AS n FROM application_documents WHERE submitted_at IS NOT NULL')).toEqual([{ n: 5 }])
  expect(workspace.query("SELECT COUNT(*) AS n FROM preparation_batch_items WHERE status = 'completed'")).toEqual([{ n: 5 }])
})
