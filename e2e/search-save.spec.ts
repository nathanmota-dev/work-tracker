import { test, expect } from './fixtures'

test('Search: direct and mixed batch saves retain criteria and selection without starting ACP', async ({ workspace, page }) => {
  await workspace.go('Search')
  await page.getByLabel('Keywords').fill('React')
  await page.getByLabel('Location', { exact: true }).fill('Remote')
  workspace.setScenario({ mcp: 'structured' })
  await page.getByRole('button', { name: 'Search LinkedIn' }).click()
  await page.getByRole('button', { name: 'Save React Engineer', exact: true }).click()
  await expect(page.getByText('1 saved · 0 already saved · 0 failed')).toBeVisible()
  const original = workspace.query('SELECT * FROM jobs')[0]!
  await page.getByRole('button', { name: `View saved job #${original.id}` }).click()
  await expect(page.getByRole('dialog')).toContainText('React Engineer')
  await page.getByRole('dialog').getByRole('button', { name: 'Close' }).click()
  workspace.setScenario({ mcp: 'mixed' })
  workspace.query("CREATE TRIGGER fail_search AFTER INSERT ON jobs WHEN NEW.title = 'Write failure' BEGIN SELECT RAISE(ABORT, 'synthetic failure'); END")
  await page.getByRole('button', { name: 'Search LinkedIn' }).click()
  await expect(page.getByRole('checkbox', { name: 'Select Incomplete role' })).toBeDisabled()
  await page.getByRole('button', { name: 'Select all savable results' }).click()
  await page.getByRole('button', { name: 'Save selected' }).click()
  await expect(page.getByText('1 saved · 1 already saved · 1 failed')).toBeVisible()
  await expect(page.getByLabel('Keywords')).toHaveValue('React')
  await expect(page.getByLabel('Location', { exact: true })).toHaveValue('Remote')
  await expect(page.getByRole('checkbox', { name: 'Select New Engineer' })).toBeChecked()
  await page.getByLabel('Search Search results').fill('Write failure')
  await workspace.fault('jobs/save-search')
  await page.getByRole('button', { name: 'Save selected' }).click()
  await expect(page.getByRole('alert')).toContainText('Synthetic transport failure')
  await expect(page.getByLabel('Search Search results')).toHaveValue('Write failure')
  await page.getByRole('button', { name: 'Save selected' }).click()
  await expect(page.getByText('0 saved · 2 already saved · 1 failed')).toBeVisible()
  expect(workspace.query('SELECT * FROM jobs')).toHaveLength(2)
  expect(workspace.query(`SELECT * FROM jobs WHERE id = ${original.id}`)).toEqual([original])
  expect(workspace.calls('prompt')).toHaveLength(0)
  expect(workspace.calls('session')).toHaveLength(0)
  await page.getByLabel('Search Search results').fill('')
  await page.getByRole('button', { name: 'View New Engineer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Assess fit with agent' })).toBeEnabled()
})

test('Search: prose-only MCP output is readable and cannot be saved', async ({ workspace, page }) => {
  workspace.setScenario({ mcp: 'prose' })
  await workspace.go('Search')
  await page.getByLabel('Keywords').fill('React')
  await page.getByRole('button', { name: 'Search LinkedIn' }).click()
  await expect(page.getByText(/Not savable — open manually/)).toBeVisible()
  await expect(page.getByText('React Engineer at Example Company https://example.com/jobs/9001', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save selected' })).toHaveCount(0)
  expect(workspace.query('SELECT * FROM jobs')).toHaveLength(0)
  expect(workspace.calls('prompt')).toHaveLength(0)
})
