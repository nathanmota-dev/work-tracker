import { test, expect } from './fixtures'
import { closeDialog, openJob, openStep } from './ui'

test.describe('workspace context', () => {
  test.use({ populated: true })

  test('Jobs → application detail → back keeps URL controls and restores drafts after an app restart', async ({ workspace, page }) => {
    workspace.query("UPDATE jobs SET status = 'saved'")
    await workspace.resize(1100, 550)
    await workspace.go('Jobs')
    await page.getByLabel('Search opportunities', { exact: true }).fill('Engineer')
    await expect(page.getByRole('article').first()).toBeVisible()
    // A card far down the list scrolls the page, so the scroll position must come back too.
    await page.getByRole('button', { name: /^View details of Engineer/ }).last().click()
    const jobsUrl = page.url()
    const scrollTop = await page.locator('[data-workspace-scroll]').evaluate(element => element.scrollTop)
    expect(scrollTop).toBeGreaterThan(0)
    await page.getByRole('dialog').getByRole('button', { name: 'View application', exact: true }).click()
    await workspace.ready('Application')
    // Each step is its own view, kept in the URL: the drafts belong to the application, not to the step.
    await openStep(page, 'Resume')
    await page.getByLabel('Additional context').fill('Synthetic first context')
    await openStep(page, 'Job description')
    await page.getByLabel('Job description', { exact: true }).fill('Synthetic unsaved description')
    await openStep(page, 'Resume')
    const applyUrl = page.url()
    await page.goBack()
    await workspace.ready('Jobs')
    await expect(page).toHaveURL(jobsUrl)
    await expect.poll(() => page.locator('[data-workspace-scroll]').evaluate(element => element.scrollTop)).toBe(scrollTop)
    await expect(page.getByRole('dialog')).toBeVisible()
    await closeDialog(page)
    await expect(page.getByLabel('Search opportunities', { exact: true })).toHaveValue('Engineer')
    await page.goForward()
    await workspace.ready('Application')
    await expect(page).toHaveURL(applyUrl)
    await expect(page.getByLabel('Additional context')).toHaveValue('Synthetic first context')
    await workspace.visit('/apply?jobId=5&step=resume', 'Application')
    await expect(page.getByLabel('Additional context')).toHaveValue('')
    await page.getByLabel('Additional context').fill('Synthetic second context')
    await page.goto(applyUrl)
    await workspace.ready('Application')
    await expect(page.getByLabel('Additional context')).toHaveValue('Synthetic first context')
    await openStep(page, 'Job description')
    await expect(page.getByLabel('Job description', { exact: true })).toHaveValue('Synthetic unsaved description')
    await workspace.restart()
    await workspace.page.goto(applyUrl)
    await workspace.ready('Application')
    await expect(workspace.page.getByLabel('Additional context')).toHaveValue('Synthetic first context')
    await openStep(workspace.page, 'Job description')
    await expect(workspace.page.getByLabel('Job description', { exact: true })).toHaveValue('Synthetic unsaved description')
    expect(workspace.query('SELECT description FROM jobs').every(row => row.description === 'React developer')).toBe(true)
    expect(workspace.calls('prompt')).toHaveLength(0)
  })

  test('Search assessment stays on the page and retains its draft across navigation', async ({ workspace, page }) => {
    workspace.setScenario({ mcp: 'structured' })
    await workspace.go('Jobs')
    await page.getByRole('button', { name: 'Discover opportunities', exact: true }).click()
    await page.getByRole('tab', { name: 'Search LinkedIn', exact: true }).click()
    await page.getByLabel('Keywords').fill('React')
    await page.getByLabel('Location', { exact: true }).fill('Remote')
    await page.getByRole('button', { name: 'Search LinkedIn' }).click()
    await expect(page.getByText('1 saved · 0 already saved · 0 failed')).toBeVisible()
    await page.getByLabel('Search opportunities', { exact: true }).fill('React Engineer')
    await page.getByRole('checkbox', { name: 'Select React Engineer', exact: true }).check()
    await openJob(page, 'React Engineer')
    await page.getByRole('dialog').getByRole('button', { name: 'Assess fit' }).click()
    const panel = page.getByRole('dialog', { name: 'Agent task' })
    await expect(panel).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Jobs', exact: true })).toBeVisible()
    await panel.getByLabel('Additional context').fill('Synthetic assessment context')
    await panel.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(panel).toBeHidden()
    await expect(page.getByRole('checkbox', { name: 'Select React Engineer', exact: true })).toBeChecked()
    // The discovery criteria are kept for the next search.
    await page.getByRole('button', { name: 'Discover opportunities', exact: true }).click()
    await page.getByRole('tab', { name: 'Search LinkedIn', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Remove React', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Remove Remote', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Back to jobs', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Select React Engineer', exact: true })).toBeChecked()
    await workspace.go('Jobs')
    await page.getByRole('button', { name: 'Open agent task' }).click()
    await expect(panel.getByLabel('Additional context')).toHaveValue('Synthetic assessment context')
    await panel.getByRole('button', { name: 'Close', exact: true }).click()
    await page.getByLabel('Search opportunities', { exact: true }).fill('')
    await openJob(page, 'Engineer 01')
    await page.getByRole('dialog').getByRole('button', { name: 'Assess fit', exact: true }).click()
    await expect(panel).toBeVisible()
    await expect(panel.getByLabel('Additional context')).toHaveValue('')
    await expect(page.getByRole('heading', { name: 'Jobs', exact: true })).toBeVisible()
    expect(workspace.calls('prompt')).toHaveLength(0)
  })
})
